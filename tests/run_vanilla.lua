-- Run from the EasyPocket directory with Lua 5.0.3 or Lua 5.1.
local passed=0
local function start(saved,mode,minimap,setup)
 -- Fresh global namespace per test; intentionally no modern globals.
 for key in pairs(_G) do
  if string.find(key,"^EasyPocket") then _G[key]=nil end
 end
 dofile("tests/vanilla_mock.lua")
 EasyPocketDB=saved
 EasyPocketMinimapDB=minimap
 dofile("Locale.lua"); dofile("Widgets.lua"); dofile("Bootstrap.lua")
 if mode~="missing" then dofile("Model.lua"); dofile("Actions.lua"); dofile("EasyPocket.lua") end
 if mode=="failure" then GetSpellName=function() error("simulated startup failure") end end
 if mode=="unsupported" then GetSpellName=nil end
 if setup then setup() end
 Event("ADDON_LOADED","EasyPocket"); Event("PLAYER_LOGIN")
 return EasyPocket
end
local function test(name,fn)
 local ok,err=pcall(fn)
 if not ok then error(name..": "..tostring(err)) end
 passed=passed+1; print("PASS "..name)
end
local function pocket(id) return EasyPocket.GetPocket(id or 1) end
local function window(id) return getglobal("EasyPocketFlyout"..(id or 1)) end
local function cell(id,col,row) return getglobal("EasyPocketSpell"..id.."_"..EasyPocket.CellIndex(col,row)) end
local function add(id,col,row,bookSlot)
 PickupSpell(bookSlot or 1,"spell"); return EasyPocket.ReceiveSpell(id,EasyPocket.CellIndex(col,row))
end
local function choose(button,index)
 Click(button); assert(EasyPocketDropdownLayer:IsShown())
 Click(getglobal("EasyPocketDropdownOption"..index))
 assert(not EasyPocketDropdownLayer:IsShown())
 assert(not EasyPocket.lastError,EasyPocket.lastError)
end
